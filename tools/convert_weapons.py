#!/usr/bin/env python3
"""Convert assets/weapons/*.png into static RGBA pixel data for the browser.

Requirements: Python 3.10+ and Pillow (python -m pip install Pillow)
Run from the repository root: python tools/convert_weapons.py
The game itself does not load PNG files; conversion happens only when this tool is run.
"""
from __future__ import annotations

import base64
import io
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "assets" / "weapons"
OUTPUT_FILE = ROOT / "weapon-pixels.js"
DEFAULT_SIZE = (32, 32)


def js_key(filename: str) -> str:
    key = re.sub(r"[^a-zA-Z0-9_$]", "_", filename)
    if not key or key[0].isdigit():
        key = "_" + key
    return key


def main() -> None:
    SOURCE_DIR.mkdir(parents=True, exist_ok=True)
    sprites: list[tuple[str, int, int, str]] = []
    for path in sorted(SOURCE_DIR.glob("*.png")):
        if path.name.startswith("."):
            continue
        with Image.open(path) as original:
            image = original.convert("RGBA")
            if image.size != DEFAULT_SIZE:
                image = image.resize(DEFAULT_SIZE, Image.Resampling.NEAREST)
            buffer = io.BytesIO()
            buffer.write(image.tobytes())
            encoded = base64.b64encode(buffer.getvalue()).decode("ascii")
            sprites.append((path.stem, image.width, image.height, encoded))

    lines = [
        "/* Generated by tools/convert_weapons.py. Do not edit by hand. */",
        "(function (global) {",
        '  const sprites = Object.create(null);',
    ]
    for name, width, height, encoded in sprites:
        key = js_key(name)
        lines.extend([
            f'  sprites["{name}"] = {{ width: {width}, height: {height},',
            f'    rgba: Uint8ClampedArray.from(atob("{encoded}"), c => c.charCodeAt(0)) }};',
        ])
    lines.extend([
        '  global.WEAPON_PIXEL_DATA = sprites;',
        '})(window);',
        '',
    ])
    OUTPUT_FILE.write_text("\n".join(lines), encoding="utf-8")
    print(f"Converted {len(sprites)} PNG file(s) -> {OUTPUT_FILE.relative_to(ROOT)}")
    for name, *_ in sprites:
        print(f" - {name}")


if __name__ == "__main__":
    main()
